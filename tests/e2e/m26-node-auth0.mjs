import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { ManagementClient } from 'auth0';
import { audience,email,password,key,decode,grant,protectedAPI,token,primary,api,fixtureFetch } from './rbac/client.mjs';
const m=new ManagementClient({domain:primary,token:await token(),maxRetries:0});
const resource=await m.resourceServers.create({name:'Plan26 protected API',identifier:audience,enforce_policies:true,token_dialect:'access_token_authz',allow_offline_access:true,skip_consent_for_verifiable_first_party_clients:true,scopes:[{value:'read:x',description:'Read X'},{value:'write:x',description:'Write X'}]});
const user=await m.users.create({connection:'Username-Password-Authentication',email,password,email_verified:true});
const second=await m.users.create({connection:'Username-Password-Authentication',email:'rbac-second@e2e.local',password,email_verified:true});
const role=await m.roles.create({name:'Plan26 Reader',description:'Runtime and migration fixture'});
assert.equal((await m.roles.get(role.id)).name,role.name);
await m.roles.update(role.id,{description:'Updated description'});
assert.equal((await m.roles.list({name_filter:'plan26',include_totals:true})).data.length,1);
await m.roles.permissions.add(role.id,{permissions:[key('read:x'),key('write:x')]});
assert.equal((await m.roles.permissions.list(role.id)).data.length,2);
await m.roles.users.assign(role.id,{users:[user.user_id]});
assert.equal((await m.roles.users.list(role.id,{take:1})).data[0].user_id,user.user_id);
await m.users.roles.assign(second.user_id,{roles:[role.id]});
assert.equal((await m.users.roles.list(second.user_id)).data[0].id,role.id);
await m.users.roles.delete(second.user_id,{roles:[role.id]});
assert.equal((await m.users.roles.list(second.user_id)).data.length,0);
await m.users.permissions.create(user.user_id,{permissions:[key('read:x')]});
let effective=(await m.users.permissions.list(user.user_id,{include_totals:true})).data;
assert.equal(effective.find(p=>p.permission_name==='read:x').sources.length,2);
await m.users.permissions.delete(user.user_id,{permissions:[key('read:x')]});
effective=(await m.users.permissions.list(user.user_id)).data;
assert.equal(effective.find(p=>p.permission_name==='read:x').sources.length,1);
await m.roles.permissions.delete(role.id,{permissions:[key('write:x')]});
assert.equal((await m.roles.permissions.list(role.id)).data.length,1);
await m.roles.permissions.add(role.id,{permissions:[key('write:x')]});
const disposable=await m.roles.create({name:'Disposable Plan26 role'});await m.roles.delete(disposable.id);
await assert.rejects(m.roles.get(disposable.id),e=>e.statusCode===404);
// Missing read:roles/read:role_members must fail even though read:users is present.
const reader=await token({id:'m24-reader',secret:'m24-reader-secret-not-for-production'},'read:users');
for(const route of [`roles/${role.id}/users`,`users/${encodeURIComponent(user.user_id)}/roles`])assert.equal((await api(route,'GET',undefined,reader)).status,403);
assert.equal((await fixtureFetch(`https://${primary}/api/v2/roles`)).status,401);
for(const dialect of ['access_token','access_token_authz','rfc9068_profile','rfc9068_profile_authz']){
 await m.resourceServers.update(resource.id,{token_dialect:dialect});
 const t=await grant();const claims=decode(t.access_token),header=JSON.parse(Buffer.from(t.access_token.split('.')[0],'base64url'));
 assert.ok(t.scope.split(' ').includes('read:x'));assert.ok(!t.scope.split(' ').includes('write:x'));
 assert.equal(header.typ,dialect.startsWith('rfc')?'at+jwt':'JWT');
 assert.equal(claims[dialect.startsWith('rfc')?'client_id':'azp'],'m26-password');
 assert.equal(claims[dialect.startsWith('rfc')?'azp':'client_id'],undefined);
 if(dialect.endsWith('_authz'))assert.deepEqual(claims.permissions,['read:x','write:x']);else assert.equal(claims.permissions,undefined);
 await protectedAPI(t.access_token,{expectedPermission:dialect.endsWith('_authz')?200:403});
 const ui=await fixtureFetch(`https://${primary}/userinfo`,{headers:{authorization:`Bearer ${t.access_token}`}});assert.equal(ui.status,200);assert.equal((await ui.json()).sub,user.user_id);
}
await m.resourceServers.update(resource.id,{token_dialect:'rfc9068_profile_authz'});
const initial=await grant();await m.users.roles.delete(user.user_id,{roles:[role.id]});
const revoked=await grant({grant_type:'refresh_token',refresh_token:initial.refresh_token});
assert.ok(!revoked.scope.split(' ').includes('read:x'));assert.deepEqual(decode(revoked.access_token).permissions,[]);
await m.users.roles.assign(user.user_id,{roles:[role.id]});
await writeFile(process.env.E2E_M26_STATE,JSON.stringify({role:role.id,user:user.user_id,resource:resource.id}),{mode:0o600});
console.log('m26 node-auth0 7.4.0: all 16 RBAC operations, source union, scoped denial, four signed profiles, actual scope/permissions middleware, userinfo and refresh revocation passed');
