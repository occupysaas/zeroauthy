import assert from 'node:assert/strict';
import { generateKeyPairSync, verify } from 'node:crypto';
import { ManagementClient } from 'auth0';
import jwks from 'jwks-rsa';
import https from 'node:https';

const domain = 'localhost:8443';
const options = { domain, clientId: 'e2e-m17-admin', clientSecret: 'e2e-m17-admin-secret-not-for-production', maxRetries: 0 };
const token = async scope => {
  const response = await fetch(`https://${domain}/oauth/token`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ grant_type: 'client_credentials', client_id: options.clientId, client_secret: options.clientSecret, audience: `https://${domain}/api/v2/`, ...(scope ? { scope } : {}) }) });
  assert.equal(response.status, 200); return (await response.json()).access_token;
};
let m = new ManagementClient(options);
const before = await m.keys.signing.list();
const old = before.find(k => k.current);
assert.ok(old?.cert && old.pkcs7 && old.fingerprint && old.thumbprint);
assert.equal((await m.keys.signing.get(old.kid)).kid, old.kid);
const oldToken = await token();
let requests = 0;
const remote = jwks({ jwksUri: `https://${domain}/.well-known/jwks.json`, cache: true, cacheMaxAge: 600_000, fetcher: async uri => { requests++; const r = await fetch(uri); assert.equal(r.status, 200); return r.json(); } });
const cached = await remote.getSigningKey(old.kid);
assert.equal(requests, 1);
const promoted = await m.keys.signing.rotate();
assert.equal(promoted.kid, before.find(k => k.next).kid);
m = new ManagementClient(options); // obtain a credential signed by the new current key
const after = await m.keys.signing.list();
const newNext = after.find(k => k.next);
assert.ok(!before.some(k => k.kid === newNext.kid));
await remote.getSigningKey(newNext.kid);
assert.equal(requests, 2, 'an unknown kid should fetch fresh JWKS');
assert.equal((await m.keys.signing.revoke(old.kid)).revoked, true);
const readsBeforeCacheHit = requests;
const retained = await remote.getSigningKey(old.kid);
assert.equal(requests, readsBeforeCacheHit, 'cached remote key is retained until cache expiry');
assert.equal(retained.getPublicKey(), cached.getPublicKey());
const [header, payload, signature] = oldToken.split('.');
assert.ok(verify('RSA-SHA256', Buffer.from(`${header}.${payload}`), retained.getPublicKey(), Buffer.from(signature, 'base64url')), 'cached public key still verifies the old mathematical signature');
const rejected = await fetch(`https://${domain}/api/v2/keys/signing`, { headers: { authorization: `Bearer ${oldToken}` } });
assert.equal(rejected.status, 401, 'local service must reject the revoked key despite external cache');
const canonical = await fetch(`https://${domain}/.well-known/jwks.json`).then(r => r.json());
assert.ok(!canonical.keys.some(k => k.kid === old.kid));
const { publicKey } = generateKeyPairSync('rsa', { modulusLength: 2048 });
const custom = { ...publicKey.export({ format: 'jwk' }), kid: 'sdk-custom-m20', alg: 'RS256', use: 'sig' };
assert.equal((await m.keys.customSigning.set({ keys: [custom] })).keys[0].kid, custom.kid);
assert.equal((await m.keys.customSigning.get()).keys[0].kid, custom.kid);
assert.ok(!(await fetch(`https://${domain}/.well-known/jwks.json`).then(r => r.json())).keys.some(k => k.kid === custom.kid));
await m.keys.customSigning.delete();
await assert.rejects(m.keys.customSigning.get(), e => e.statusCode === 404);
const reader = new ManagementClient({ domain, token: await token('read:signing_keys'), maxRetries: 0 });
assert.ok((await reader.keys.signing.list()).length > 0);
await assert.rejects(reader.keys.signing.rotate(), e => e.statusCode === 403);
await assert.rejects(reader.keys.signing.revoke(promoted.kid), e => e.statusCode === 403);
await assert.rejects(reader.keys.customSigning.set({ keys: [custom] }), e => e.statusCode === 403);
await assert.rejects(reader.keys.customSigning.delete(), e => e.statusCode === 403);
const noSigning = new ManagementClient({ domain, token: await token('read:tenant_settings'), maxRetries: 0 });
await assert.rejects(noSigning.keys.signing.list(), e => e.statusCode === 403);
await assert.rejects(noSigning.keys.signing.get(promoted.kid), e => e.statusCode === 403);
await assert.rejects(noSigning.keys.customSigning.get(), e => e.statusCode === 403);
const wrongTenantToken = await token();
const crossTenantStatus = await new Promise((resolve, reject) => {
  const req = https.request({ hostname: 'localhost', servername: 'localhost', port: 8443, path: '/api/v2/keys/signing', headers: { host: 'cli.e2e.test', authorization: `Bearer ${wrongTenantToken}` } }, res => { res.resume(); resolve(res.statusCode); });
  req.on('error', reject); req.end();
});
assert.equal(crossTenantStatus, 401);
assert.equal((await m.rules.list({ include_totals: true })).data.length, 0);
assert.equal((await m.hooks.list({ include_totals: true })).data.length, 0);
console.log('m20-node-auth0: seven key endpoints, scoped/tenant refusals, retired collections, unknown-kid refresh and remote-cache revocation boundary passed');
