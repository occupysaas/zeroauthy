import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {setGlobalDispatcher} from 'undici';
import {ManagementClient} from 'auth0';
import {token,primary,fixtureDispatcher,email,password} from './organizations/client.mjs';
setGlobalDispatcher(fixtureDispatcher);
const m=new ManagementClient({domain:primary,token:await token(),maxRetries:0}),o=m.organizations;
const connection=(await m.connections.list()).data.find(c=>c.name==='Username-Password-Authentication');
const user=await m.users.create({connection:connection.name,email,password,email_verified:true});
const outsider=await m.users.create({connection:connection.name,email:'organizations-outsider@e2e.local',password,email_verified:true});
const role=await m.roles.create({name:'Plan29 Reader'});
const org=await o.create({name:'sdk-org',display_name:'SDK Organization',metadata:{source:'sdk'}});
assert.equal((await o.get(org.id)).name,'sdk-org');
assert.equal((await o.getByName('sdk-org')).id,org.id);
await o.update(org.id,{display_name:'SDK Updated'});
assert.equal((await o.list({include_totals:true,per_page:100})).data.find(x=>x.id===org.id).display_name,'SDK Updated');
await o.enabledConnections.add(org.id,{connection_id:connection.id});
assert.equal((await o.enabledConnections.get(org.id,connection.id)).assign_membership_on_login,false);
await o.enabledConnections.update(org.id,connection.id,{assign_membership_on_login:true});
assert.equal((await o.enabledConnections.list(org.id,{include_totals:true})).data[0].assign_membership_on_login,true);
await o.enabledConnections.delete(org.id,connection.id);
await o.connections.create(org.id,{connection_id:connection.id});
assert.equal((await o.connections.get(org.id,connection.id)).connection_id,connection.id);
await o.connections.update(org.id,connection.id,{assign_membership_on_login:true});
assert.equal((await o.connections.list(org.id,{include_totals:true})).data[0].assign_membership_on_login,true);
await o.connections.delete(org.id,connection.id);
await o.enabledConnections.add(org.id,{connection_id:connection.id});
await o.members.create(org.id,{members:[user.user_id]});
assert.equal((await o.members.list(org.id,{include_totals:true})).data[0].user_id,user.user_id);
await o.members.roles.assign(org.id,user.user_id,{roles:[role.id]});
assert.equal((await o.members.roles.list(org.id,user.user_id)).data[0].id,role.id);
const effective=await o.members.effectiveRoles.list(org.id,user.user_id,{take:1});
assert.equal(effective.data[0].id,role.id);assert.deepEqual(effective.data[0].sources,['direct']);
assert.equal((await o.roles.members.list(org.id,role.id,{take:1})).data[0].user_id,user.user_id);
assert.equal((await m.users.organizations.list(user.user_id)).data[0].id,org.id);
await o.members.roles.delete(org.id,user.user_id,{roles:[role.id]});
assert.equal((await o.members.roles.list(org.id,user.user_id)).data.length,0);
await o.members.delete(org.id,{members:[user.user_id]});
assert.equal((await o.members.list(org.id)).data.length,0);
await o.delete(org.id);await assert.rejects(o.get(org.id),e=>e.statusCode===404);
const fixtures={};
for(const [name,display,automatic,signup] of [['alpha','Alpha Organization',false,false],['beta','Beta Organization',false,false],['automatic','Automatic Organization',true,false],['signup','Signup Organization',true,true]]){
 const x=await o.create({name,display_name:display,branding:{colors:{primary:'#123456',page_background:'#f0e0d0'}}});
 await o.enabledConnections.add(x.id,{connection_id:connection.id,assign_membership_on_login:automatic,is_signup_enabled:signup});
 if(name==='alpha'||name==='beta')await o.members.create(x.id,{members:[user.user_id]});
 fixtures[name]=x.id;
}
await o.members.roles.assign(fixtures.alpha,user.user_id,{roles:[role.id]});
await writeFile(process.env.E2E_M29_STATE,JSON.stringify({...fixtures,user:user.user_id,outsider:outsider.user_id,role:role.id,connection:connection.id}),{mode:0o600});
console.log('Plan29 node-auth0 7.4.0: organization CRUD/by-name/list; both 5-method connection resources; members, roles, effective roles, role members, user organizations passed');
console.log('Plan29 deferred SDK methods: search, invitations, clients/clientGrants writes, discoveryDomains, groups remain outside scope');
